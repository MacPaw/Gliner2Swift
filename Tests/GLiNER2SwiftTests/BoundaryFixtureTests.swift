// BoundaryFixtureTests.swift
// Stage-by-stage parity of the GLiNER2.5 boundary path against Python gliner2 2.0.0.
//
// Fixtures: Tests/GLiNER2SwiftTests/Fixtures/boundary/small/<case>.{safetensors,json},
// generated by scripts/generate_boundary_fixtures.py against fastino/gliner2.5-small-v1
// in fp32 on the CPU. Every intermediate the head produces is pinned, so a divergence is
// attributed to the first stage that drifts rather than discovered at the output.
//
// Run:
//   xcodebuild test -scheme GLiNER2Swift -destination 'platform=macOS' \
//     -only-testing:GLiNER2SwiftTests/BoundaryFixtureTests

import XCTest
import Foundation
import MLX
@testable import GLiNER2Swift

final class BoundaryFixtureTests: XCTestCase {

    // MARK: - Tolerances (fp32 Swift/MLX vs fp32 PyTorch CPU)

    /// Encoder-derived states (text/query/boundary states).
    private let stateTolerance: Float = 2e-3
    /// Logits, prefix sums and scores.
    private let logitTolerance: Float = 5e-3
    /// Confidences in the formatted output.
    private let confidenceTolerance: Double = 2e-3

    /// Cases whose formatted output is known to diverge until a later phase lands. A case
    /// listed here that starts passing fails the suite so the list cannot rot.
    private static let expectedOutputFailures: [String: String] = [:]

    // MARK: - Model (loaded once per process)

    private static var cachedModel: GLiNER2?

    private func loadModel() async throws -> GLiNER2 {
        if let cached = Self.cachedModel { return cached }
        try TestModel.requireGPU()
        let path = try TestModel.requireBoundaryModel("small")
        let model = try await GLiNER2.fromPretrained(path, strict: true)
        XCTAssertEqual(model.config.architecture, .boundary)
        XCTAssertNotNil(model.boundaryModel)
        Self.cachedModel = model
        return model
    }

    // MARK: - Fixture loading

    private struct Fixture {
        let name: String
        let sidecar: [String: Any]
        let tensors: [String: MLXArray]

        var texts: [String] { sidecar["texts"] as? [String] ?? [] }
        var threshold: Float { Float(sidecar["threshold"] as? Double ?? 0.5) }
        var kind: String { sidecar["kind"] as? String ?? "standard" }
        /// One schema dict per text (batch case) or the single schema for every text.
        func schemaDict(sample: Int) -> [String: Any] {
            if let list = sidecar["schemas"] as? [[String: Any]], sample < list.count { return list[sample] }
            return sidecar["schema"] as? [String: Any] ?? [:]
        }
        func metadataDict(sample: Int) -> [String: Any] {
            if let list = sidecar["metadata"] as? [[String: Any]], sample < list.count { return list[sample] }
            return sidecar["metadata"] as? [String: Any] ?? [:]
        }
        func tensor(_ name: String) -> MLXArray? { tensors[name] }
        func floats(_ name: String) -> [Float]? { tensors[name]?.asType(.float32).asArray(Float.self) }
        func ints(_ name: String) -> [Int32]? { tensors[name]?.asType(.int32).asArray(Int32.self) }
    }

    private func loadFixture(_ name: String) throws -> Fixture {
        let dir = TestModel.boundaryFixturesDirectory("small")
        let jsonURL = dir.appendingPathComponent("\(name).json")
        guard FileManager.default.fileExists(atPath: jsonURL.path) else {
            throw XCTSkip("fixture \(name).json not found; regenerate with scripts/generate_boundary_fixtures.py")
        }
        let sidecar = try JSONSerialization.jsonObject(with: Data(contentsOf: jsonURL)) as? [String: Any] ?? [:]
        let tensorsURL = dir.appendingPathComponent("\(name).safetensors")
        let tensors = FileManager.default.fileExists(atPath: tensorsURL.path)
            ? try MLX.loadArrays(url: tensorsURL) : [:]
        return Fixture(name: name, sidecar: sidecar, tensors: tensors)
    }

    private func standardCases() throws -> [String] {
        let dir = TestModel.boundaryFixturesDirectory("small")
        let manifestURL = dir.appendingPathComponent("manifest.json")
        guard let data = try? Data(contentsOf: manifestURL),
              let manifest = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
              let cases = manifest["cases"] as? [String: Any] else {
            throw XCTSkip("fixture manifest not found at \(manifestURL.path)")
        }
        return cases.compactMap { name, info -> String? in
            let kind = (info as? [String: Any])?["kind"] as? String ?? "standard"
            return kind == "standard" ? name : nil
        }.sorted()
    }

    // MARK: - Schema reconstruction (Python Schema DSL → Swift Schema)

    /// Rebuild the Swift schema from the built dict plus the recorded metadata, so field
    /// dtypes, choices and thresholds (which the raw dict does not carry) round-trip.
    static func buildSchema(dict: [String: Any], metadata: [String: Any]) -> Schema {
        var schema = Schema()

        let entityMeta = metadata["entity_metadata"] as? [String: [String: Any]] ?? [:]
        var entityOrder = metadata["entity_order"] as? [String] ?? []
        if entityOrder.isEmpty, let entities = dict["entities"] as? [String: Any] {
            entityOrder = entities.keys.sorted()
        }
        if !entityOrder.isEmpty {
            let descriptions = dict["entity_descriptions"] as? [String: String] ?? [:]
            if descriptions.isEmpty {
                schema = schema.entities(entityOrder)
            } else {
                // Ordered descriptions: the DSL's dictionary form loses order, so add
                // the entity list first and attach descriptions to the built dict.
                schema = schema.entities(entityOrder)
                var dict = schema.internalSchemaDict
                dict["entity_descriptions"] = descriptions
                schema.internalSchemaDict = dict
            }
            for name in entityOrder {
                if let meta = entityMeta[name], let thr = meta["threshold"] as? Double {
                    schema.metadata.entityMetadata[name]?.threshold = Float(thr)
                }
                if let meta = entityMeta[name], let dtype = meta["dtype"] as? String {
                    schema.metadata.entityMetadata[name]?.dtype = dtype
                }
            }
        }

        let fieldMeta = metadata["field_metadata"] as? [String: [String: Any]] ?? [:]
        let fieldOrders = metadata["field_orders"] as? [String: [String]] ?? [:]
        for structure in dict["json_structures"] as? [[String: Any]] ?? [] {
            for (name, fieldsAny) in structure {
                let fields = fieldsAny as? [String: Any] ?? [:]
                let order = fieldOrders[name] ?? fields.keys.sorted()
                var builder = schema.structure(name)
                for field in order {
                    let meta = fieldMeta["\(name).\(field)"] ?? [:]
                    var choices = meta["choices"] as? [String]
                    if choices == nil, let spec = fields[field] as? [String: Any] {
                        choices = spec["choices"] as? [String]
                    }
                    builder = builder.field(
                        field,
                        dtype: meta["dtype"] as? String ?? "list",
                        choices: choices,
                        description: nil,
                        threshold: (meta["threshold"] as? Double).map { Float($0) })
                }
                schema = builder.done()
            }
        }

        var relationOrder = metadata["relation_order"] as? [String] ?? []
        if relationOrder.isEmpty {
            for relation in dict["relations"] as? [[String: Any]] ?? [] {
                relationOrder += relation.keys.sorted()
            }
        }
        if !relationOrder.isEmpty {
            schema = schema.relations(relationOrder)
        }

        for cls in dict["classifications"] as? [[String: Any]] ?? [] {
            guard let task = cls["task"] as? String, let labels = cls["labels"] as? [String] else { continue }
            schema = schema.classification(
                task: task, labels: labels,
                multiLabel: cls["multi_label"] as? Bool ?? false,
                threshold: Float(cls["cls_threshold"] as? Double ?? 0.5))
        }
        return schema
    }

    // MARK: - Comparison helpers

    /// Python's expected output re-decoded through `JSONDecoder`, so integers stay
    /// numbers (`JSONValue(swiftValue:)` would read an `NSNumber` 0/1 as a Bool).
    static func jsonValue(_ any: Any) -> JSONValue {
        guard JSONSerialization.isValidJSONObject(any),
              let data = try? JSONSerialization.data(withJSONObject: any),
              let value = try? JSONDecoder().decode(JSONValue.self, from: data) else {
            return JSONValue(swiftValue: any)
        }
        return value
    }

    private func maxAbsDiff(_ a: [Float], _ b: [Float]) -> Float {
        guard a.count == b.count else { return .infinity }
        var worst: Float = 0
        for i in 0..<a.count { worst = max(worst, abs(a[i] - b[i])) }
        return worst
    }

    /// Compare an MLX array against the fixture tensor over an optional leading slice of
    /// each of the first two axes (the valid, unpadded region).
    private func assertClose(
        _ actual: MLXArray, fixture: Fixture, key: String, tolerance: Float,
        file: StaticString = #filePath, line: UInt = #line
    ) {
        guard let expected = fixture.tensor(key) else {
            XCTFail("[\(fixture.name)] fixture has no tensor \(key)", file: file, line: line)
            return
        }
        guard actual.shape == expected.shape else {
            XCTFail("[\(fixture.name)] \(key): shape \(actual.shape) vs fixture \(expected.shape)",
                    file: file, line: line)
            return
        }
        let diff = maxAbsDiff(actual.asType(.float32).asArray(Float.self),
                              expected.asType(.float32).asArray(Float.self))
        XCTAssertLessThanOrEqual(diff, tolerance,
                                 "[\(fixture.name)] \(key): max |Δ| = \(diff)", file: file, line: line)
    }

    private func assertIntsEqual(
        _ actual: MLXArray, fixture: Fixture, key: String,
        file: StaticString = #filePath, line: UInt = #line
    ) {
        guard let expected = fixture.ints(key) else {
            XCTFail("[\(fixture.name)] fixture has no tensor \(key)", file: file, line: line)
            return
        }
        let got = actual.asType(.int32).asArray(Int32.self)
        XCTAssertEqual(got, expected, "[\(fixture.name)] \(key) differs", file: file, line: line)
    }

    // MARK: - The pipeline, stage by stage

    /// Run the Swift pipeline exactly as Python's fixture generator did (no bucket padding,
    /// so shapes match the fixture) and compare every stage.
    private func checkStages(_ fixture: Fixture, model: GLiNER2) throws {
        guard let boundary = model.boundaryModel else { return XCTFail("not a boundary model") }
        let texts = fixture.texts
        XCTAssertFalse(texts.isEmpty, "[\(fixture.name)] no texts")

        // Processor.
        var records: [TransformedRecord] = []
        var schemas: [Schema] = []
        for (i, text) in texts.enumerated() {
            let schema = Self.buildSchema(dict: fixture.schemaDict(sample: i),
                                          metadata: fixture.metadataDict(sample: i))
            schemas.append(schema)
            records.append(model.processor.transform(text: GLiNER2.normalizeText(text),
                                                     schema: schema.build()))
        }
        let batch = model.processor.collateBatch(records)

        // Token ids (compare the unpadded prefix of every row).
        if let ids = fixture.ints("input_ids"), let mask = fixture.ints("attention_mask"),
           let shape = fixture.tensor("input_ids")?.shape, shape.count == 2 {
            let S = shape[1]
            for i in 0..<texts.count {
                let length = (0..<S).filter { mask[i * S + $0] != 0 }.count
                let expected = Array(ids[(i * S)..<(i * S + length)]).map { Int($0) }
                XCTAssertEqual(batch.inputIdsCPU[i], expected,
                               "[\(fixture.name)] sample \(i): input_ids differ")
            }
        }

        // Routing tensors.
        let metadata = schemas[0].metadata
        let inputs = BoundaryBatchInputs.build(
            from: batch, metadata: metadata, threshold: fixture.threshold,
            wordGranularity: 1, queryGranularity: 1)
        assertIntsEqual(inputs.textWordIndices, fixture: fixture, key: "text_word_indices")
        assertIntsEqual(inputs.textWordMask, fixture: fixture, key: "text_word_mask")
        let hasQueries = inputs.queryLayouts.contains(where: { !$0.isEmpty })
        if hasQueries || fixture.tensor("query_marker_indices") != nil {
            assertIntsEqual(inputs.queryMarkerIndices, fixture: fixture, key: "query_marker_indices")
            assertIntsEqual(inputs.queryMask, fixture: fixture, key: "query_marker_mask")
        }
        if let offsets = fixture.sidecar["word_offsets"] as? [Int] {
            XCTAssertEqual(inputs.wordOffsets, offsets, "[\(fixture.name)] word_offsets")
        }
        // Python pads the threshold tensor to the batch's widest query row; compare the
        // real queries of every sample.
        if let thresholds = fixture.sidecar["query_thresholds"] as? [[Double]] {
            for (i, row) in thresholds.enumerated() where i < inputs.queryThresholds.count {
                let ours = inputs.queryThresholds[i]
                XCTAssertLessThanOrEqual(ours.count, row.count,
                                         "[\(fixture.name)] sample \(i): query count \(ours.count) vs \(row.count)")
                for (q, t) in row.enumerated() where q < ours.count {
                    XCTAssertEqual(ours[q], Float(t), accuracy: 1e-6, "[\(fixture.name)] threshold q\(q)")
                }
            }
        }
        // Query layout.
        if let layouts = fixture.sidecar["query_layout"] as? [[[String: Any]]] {
            for (i, layout) in layouts.enumerated() where i < inputs.queryLayouts.count {
                let ours = inputs.queryLayouts[i]
                XCTAssertEqual(ours.count, layout.count, "[\(fixture.name)] sample \(i): query layout size")
                for (q, spec) in layout.enumerated() where q < ours.count {
                    XCTAssertEqual(ours[q].taskType, spec["task_type"] as? String, "[\(fixture.name)] q\(q) task_type")
                    XCTAssertEqual(ours[q].taskName, spec["task_name"] as? String, "[\(fixture.name)] q\(q) task_name")
                    XCTAssertEqual(ours[q].roleName, spec["role_name"] as? String, "[\(fixture.name)] q\(q) role_name")
                    XCTAssertEqual(ours[q].taskIndex, spec["task_index"] as? Int, "[\(fixture.name)] q\(q) task_index")
                }
            }
        }

        guard hasQueries else { return }

        // Encoder + routing gathers.
        let hidden = model.model.encode(batch.inputIds, attentionMask: batch.attentionMask).lastHiddenState
        let core = boundary.encodeCore(hiddenStates: hidden, inputs: inputs)
        assertClose(core.textStates, fixture: fixture, key: "text_states", tolerance: stateTolerance)
        assertClose(core.queryStates, fixture: fixture, key: "query_states", tolerance: stateTolerance)

        // Head, module by module.
        let out = boundary.score(core)
        assertIntsEqual(out.boundary.mask, fixture: fixture, key: "boundary_mask")
        assertClose(out.boundary.states, fixture: fixture, key: "boundary_states", tolerance: stateTolerance)
        assertClose(out.marginals.startLogits, fixture: fixture, key: "start_logits", tolerance: logitTolerance)
        assertClose(out.marginals.endLogits, fixture: fixture, key: "end_logits", tolerance: logitTolerance)
        assertClose(out.marginals.insideLogits, fixture: fixture, key: "inside_logits", tolerance: logitTolerance)
        assertClose(out.marginals.insidePrefix, fixture: fixture, key: "inside_prefix", tolerance: logitTolerance)
        assertClose(out.marginals.insidePrefixMean, fixture: fixture, key: "inside_prefix_mean", tolerance: logitTolerance)

        // Pool: the set of valid spans must match exactly; order too, except within ties.
        checkPool(out, fixture: fixture)
        assertClose(out.pooled.compatLogits, fixture: fixture, key: "pool_compat_logits", tolerance: logitTolerance)
        assertClose(out.pooled.proposalLogits, fixture: fixture, key: "pool_proposal_logits", tolerance: logitTolerance)

        assertClose(out.scorerCandidate, fixture: fixture, key: "scorer_candidate", tolerance: logitTolerance)
        assertClose(out.scorerScore, fixture: fixture, key: "scorer_score", tolerance: logitTolerance)
        assertClose(out.pairLogits, fixture: fixture, key: "pair_logits", tolerance: logitTolerance)
        assertClose(out.nullLogits, fixture: fixture, key: "null_logits", tolerance: logitTolerance)
        assertClose(out.countLogRates, fixture: fixture, key: "count_log_rates", tolerance: logitTolerance)
        if fixture.tensor("candidate_states") != nil {
            assertClose(out.candidateStates, fixture: fixture, key: "candidate_states", tolerance: logitTolerance)
        }
        let probs = MLX.sigmoid(out.pairLogits.asType(.float32) / boundary.settings.pairTemperature)
        assertClose(probs, fixture: fixture, key: "probs", tolerance: logitTolerance)

        // Explicit-span scoring (the per-query proposer + pair reranker), on the spans the
        // generator picked: the pool's first valid spans broadcast over every query.
        if let explicitIndices = fixture.tensor("explicit_indices") {
            let validMask = fixture.tensor("explicit_mask").map { $0.asType(.bool) }
            let logits = boundary.scoreExplicitSpans(core, indices: explicitIndices.asType(.int32), validMask: validMask)
            assertClose(logits, fixture: fixture, key: "explicit_logits", tolerance: logitTolerance)
        }
    }

    private func checkPool(_ out: BoundaryHead.Output, fixture: Fixture) {
        guard let expectedIdx = fixture.ints("pool_indices"), let expectedMask = fixture.ints("pool_mask"),
              let shape = fixture.tensor("pool_indices")?.shape else {
            return XCTFail("[\(fixture.name)] pool fixtures missing")
        }
        let B = shape[0], P = shape[1]
        XCTAssertEqual(out.indices.shape, shape, "[\(fixture.name)] pool_indices shape")
        let ours = out.indices.asType(.int32).asArray(Int32.self)
        let ourMask = out.validMask.asArray(Bool.self)
        for b in 0..<B {
            var expectedSet: Set<[Int32]> = []
            var expectedSeq: [[Int32]] = []
            var ourSet: Set<[Int32]> = []
            var ourSeq: [[Int32]] = []
            for c in 0..<P {
                let base = (b * P + c) * 2
                if expectedMask[b * P + c] != 0 {
                    expectedSet.insert([expectedIdx[base], expectedIdx[base + 1]])
                    expectedSeq.append([expectedIdx[base], expectedIdx[base + 1]])
                }
                if ourMask[b * P + c] {
                    ourSet.insert([ours[base], ours[base + 1]])
                    ourSeq.append([ours[base], ours[base + 1]])
                }
            }
            XCTAssertEqual(ourSet.count, ourSeq.count, "[\(fixture.name)] sample \(b): duplicate spans in pool")
            XCTAssertEqual(ourSet, expectedSet,
                           "[\(fixture.name)] sample \(b): pool set differs "
                           + "(missing \(expectedSet.subtracting(ourSet).count), extra \(ourSet.subtracting(expectedSet).count))")
            if ourSet == expectedSet && ourSeq != expectedSeq {
                // Same members, different order: only acceptable across exact score ties.
                let firstDiff = Array(zip(ourSeq, expectedSeq)).firstIndex { $0 != $1 } ?? -1
                XCTFail("[\(fixture.name)] sample \(b): pool order differs from position \(firstDiff): "
                        + "ours \(ourSeq[max(firstDiff, 0)]) vs \(expectedSeq[max(firstDiff, 0)])")
            }
        }
    }

    // MARK: - Formatted output

    private func checkOutput(_ fixture: Fixture, model: GLiNER2) -> [String] {
        guard let expectedList = fixture.sidecar["expected_formatted"] as? [Any] else {
            return ["[\(fixture.name)] no expected_formatted in sidecar"]
        }
        var problems: [String] = []
        for (i, text) in fixture.texts.enumerated() where i < expectedList.count {
            let schema = Self.buildSchema(dict: fixture.schemaDict(sample: i),
                                          metadata: fixture.metadataDict(sample: i))
            let actual = model.extract(text: text, schema: schema, threshold: fixture.threshold,
                                       includeConfidence: true, includeSpans: true)
            problems += PredictionParityTests.diff(
                expected: Self.jsonValue(expectedList[i]),
                actual: JSONValue(swiftValue: actual),
                path: "\(fixture.name)[\(i)]",
                confidenceTolerance: confidenceTolerance)
        }
        return problems
    }

    // MARK: - Tests

    func testStagesMatchPython() async throws {
        let model = try await loadModel()
        for name in try standardCases() {
            let fixture = try loadFixture(name)
            try checkStages(fixture, model: model)
        }
    }

    func testFormattedOutputMatchesPython() async throws {
        let model = try await loadModel()
        var failures: [String] = []
        var unexpectedPasses: [String] = []
        for name in try standardCases() {
            let fixture = try loadFixture(name)
            let problems = checkOutput(fixture, model: model)
            if let phase = Self.expectedOutputFailures[name] {
                if problems.isEmpty { unexpectedPasses.append("\(name) [\(phase)]") }
                else { print("  [expected: \(phase)] \(name): \(problems.count) mismatch(es)") }
            } else if !problems.isEmpty {
                failures.append("\(name):\n    " + problems.prefix(8).joined(separator: "\n    "))
            }
        }
        XCTAssertTrue(unexpectedPasses.isEmpty,
                      "now passing — remove from expectedOutputFailures:\n" + unexpectedPasses.joined(separator: "\n"))
        XCTAssertTrue(failures.isEmpty, "formatted output diverges:\n\n" + failures.joined(separator: "\n\n"))
    }

    /// Long-document chunking (384 / 64) through `extractLong` against Python's
    /// `extract_entities_long` on the same text.
    func testChunkedDocumentMatchesPython() async throws {
        let model = try await loadModel()
        let fixture = try loadFixture("doc_1200_chunked")
        guard let text = fixture.sidecar["text"] as? String,
              let expected = fixture.sidecar["expected_formatted"] else {
            throw XCTSkip("doc_1200_chunked sidecar incomplete")
        }
        let entityTypes = fixture.sidecar["entity_types"] as? [String]
            ?? (fixture.schemaDict(sample: 0)["entities"] as? [String: Any])?.keys.sorted() ?? []
        let chunkSize = fixture.sidecar["chunk_size"] as? Int ?? 384
        let overlap = fixture.sidecar["chunk_overlap"] as? Int ?? 64
        let actual = model.extractEntitiesLong(
            text: text, entityTypes: entityTypes, chunkSize: chunkSize, overlap: overlap,
            threshold: fixture.threshold, includeConfidence: true, includeSpans: true)
        let expectedValue: Any = (expected as? [Any])?.first ?? expected
        let problems = PredictionParityTests.diff(
            expected: Self.jsonValue(expectedValue), actual: JSONValue(swiftValue: actual),
            path: "doc_1200_chunked", confidenceTolerance: confidenceTolerance)
        XCTAssertTrue(problems.isEmpty, problems.prefix(12).joined(separator: "\n"))
    }
}
